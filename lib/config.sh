# shellcheck shell=bash
# Answers, secrets, generated secrets, prompts, value checks and version holds.
# Sourced by ./kit after common.sh.
#
# Machine files (none of them in the repo checkout):
#   answers.conf                 user-owned: choices. The kit only appends missing keys and edits
#                                the MODULES= line.
#   secrets.conf (600)           user-owned: keys the user supplies. The kit only appends missing keys.
#   kit/generated-secrets.conf   seeded (600): random app secrets, each created once, never changed.
#
# A module's prompts file declares what it needs, one entry per line:
#   file|key|default|validator|question|when
#     file       answers | secrets | gen
#     default    "~/..." is expanded to the home folder; "!name" calls default_<name>.
#                For gen entries: the secret's format (hex16, hex24, hex32, alnum24, password24, apikey).
#     validator  see validate(); a leading "?" makes the value optional (Enter skips it)
#     question   empty: never asked; the default applies without being written down
#     when       optional KEY=value or KEY!=value, tested against answers, or KEY? (KEY is set)

SERVER_DIR=${KIT_SERVER_DIR:-$HOME/server}
KIT_STATE=$SERVER_DIR/kit
ANSWERS=$SERVER_DIR/answers.conf
SECRETS=$SERVER_DIR/secrets.conf
GEN_SECRETS=$KIT_STATE/generated-secrets.conf

ANSWERS_HEADER='# mac-server-kit answers for this machine. Yours to edit; ./kit install re-reads it.
# The kit only ever appends keys that are missing here and edits the MODULES= line.
# Format: KEY=value, one per line. Put a value in double quotes to keep a " #" in it.'

SECRETS_HEADER='# mac-server-kit secrets for this machine (keep this file private: chmod 600).
# The kit only ever appends keys that are missing. Format: KEY="value", one per line.'

GEN_HEADER='# Generated by ./kit: random app secrets, created once and never changed.
# Losing this file loses database passwords and the Homarr encryption key; backup-config keeps it.'

config_init() {
    mkdir -p "$SERVER_DIR" "$KIT_STATE" || die "could not create $SERVER_DIR"
    chmod 700 "$KIT_STATE"
    [ -f "$ANSWERS" ] || printf '%s\n\n' "$ANSWERS_HEADER" >"$ANSWERS" || die "could not create $ANSWERS"
    if [ ! -f "$SECRETS" ]; then
        (umask 077; printf '%s\n\n' "$SECRETS_HEADER" >"$SECRETS") || die "could not create $SECRETS"
    fi
    if [ ! -f "$GEN_SECRETS" ]; then
        (umask 077; printf '%s\n\n' "$GEN_HEADER" >"$GEN_SECRETS") || die "could not create $GEN_SECRETS"
    fi
    chmod 600 "$SECRETS" "$GEN_SECRETS" || die "could not set permissions on the secrets files"
}

# --secrets <file> / --answers <file>: use a file the user filled in (often from a template).
# An existing ~/server file is never overwritten: the same file is fine, a different one stops the
# install. A new one becomes a draft in ~/server/kit/ for this run (prompts append to the draft),
# and is copied into place only by import_commit, once every value has passed its check. So an
# install that's quit or stopped by a bad value leaves nothing behind: fix the file, run it again.
ANSWERS_FROM=''     # the user's file while answers.conf is still a draft ("" otherwise)
SECRETS_FROM=''
import_user_file() {        # source destination mode which(ANSWERS|SECRETS)
    local src=$1 dest=$2 draft
    [ -f "$src" ] || die "no file at $src"
    if [ -f "$dest" ]; then
        if [ "$(cd "$(dirname "$src")" && pwd -P)/$(basename "$src")" = "$(cd "$(dirname "$dest")" && pwd -P)/$(basename "$dest")" ]; then
            return 0
        fi
        cmp -s "$src" "$dest" && return 0
        die "$(tilde "$dest") already exists and differs from $src. Install reads $(tilde "$dest"), and the kit never overwrites it: make your change there (or merge the two by hand), then run ./kit install without $([ "$4" = SECRETS ] && echo --secrets || echo --answers)."
    fi
    { mkdir -p "$KIT_STATE" && chmod 700 "$KIT_STATE"; } || die "could not create $KIT_STATE"
    draft=$KIT_STATE/draft-$(basename "$dest")
    (umask 077; cp "$src" "$draft") || die "could not copy $src"
    chmod "$3" "$draft"
    printf -v "$4" '%s' "$draft"
    printf -v "${4}_FROM" '%s' "$src"
}
import_secrets_file() { import_user_file "$1" "$SERVER_DIR/secrets.conf" 600 SECRETS; }
import_answers_file() { import_user_file "$1" "$SERVER_DIR/answers.conf" 644 ANSWERS; }

# After the values have passed: move the drafts into place.
import_commit() {
    if [ -n "$ANSWERS_FROM" ]; then
        mv -f "$ANSWERS" "$SERVER_DIR/answers.conf" || die "could not write $SERVER_DIR/answers.conf"
        ok "Copied $ANSWERS_FROM to $(tilde "$SERVER_DIR/answers.conf")"
        ANSWERS=$SERVER_DIR/answers.conf ANSWERS_FROM=''
    fi
    if [ -n "$SECRETS_FROM" ]; then
        mv -f "$SECRETS" "$SERVER_DIR/secrets.conf" || die "could not write $SERVER_DIR/secrets.conf"
        ok "Copied $SECRETS_FROM to $(tilde "$SERVER_DIR/secrets.conf")"
        SECRETS=$SERVER_DIR/secrets.conf SECRETS_FROM=''
    fi
}

# A file's name for messages: the user's own file while it's still a draft.
shown() {           # path
    if [ -n "$ANSWERS_FROM" ] && [ "$1" = "$ANSWERS" ]; then printf '%s' "$ANSWERS_FROM"; return; fi
    if [ -n "$SECRETS_FROM" ] && [ "$1" = "$SECRETS" ]; then printf '%s' "$SECRETS_FROM"; return; fi
    tilde "$1"
}

# ---------------------------------------------------------------- lookups

prompt_entry() {    # file key -> the first matching prompts line among all discovered modules
    local m
    for m in $MODULES_ALL; do
        [ -f "$(mod_dir "$m")/prompts" ] || continue
        awk -F'|' -v f="$1" -v k="$2" '$1 == f && $2 == k { print; found = 1; exit } END { exit !found }' \
            "$(mod_dir "$m")/prompts" && return 0
    done
    return 1
}

# Answers for a run that isn't this machine's (./kit prepare --vpn ..., say): KEY=value lines.
ANSWER_OVERRIDES=''
override_answer() {     # key value
    ANSWER_OVERRIDES=$(printf '%s\n' "$ANSWER_OVERRIDES" | awk -F= -v k="$1" 'NF && $1 != k')
    ANSWER_OVERRIDES="${ANSWER_OVERRIDES:+$ANSWER_OVERRIDES
}$1=$2"
}

# key -> the answer (an override, answers.conf, or the default its prompt declares), normalized
# the way its validator expects (so "~/Media" in answers.conf means the home folder).
answer() {
    local line spec val
    if val=$(printf '%s\n' "$ANSWER_OVERRIDES" | awk -v k="$1" 'index($0, k "=") == 1 { v = substr($0, length(k) + 2); f = 1 } END { if (!f) exit 1; printf "%s", v }'); then
        :
    elif val=$(kv_get "$ANSWERS" "$1"); then
        :
    else
        line=$(prompt_entry answers "$1") || return 1
        val=$(expand_default "$(printf '%s' "$line" | cut -d'|' -f3)")
    fi
    line=$(prompt_entry answers "$1") && spec=$(printf '%s' "$line" | cut -d'|' -f4) || spec=''
    normalize_value "$spec" "$val"
}

secret() {          # key -> from secrets.conf, else generated-secrets.conf
    kv_get "$SECRETS" "$1" || kv_get "$GEN_SECRETS" "$1"
}

expand_default() {
    # shellcheck disable=SC2088  # a literal "~" in the default, expanded here
    case "$1" in
        '!'*) "default_${1#!}" ;;
        '~') printf '%s' "$HOME" ;;
        '~/'*) printf '%s/%s' "$HOME" "${1#\~/}" ;;
        *) printf '%s' "$1" ;;
    esac
}

default_tz() {      # this Mac's time zone, from /etc/localtime
    local tz
    tz=$(readlink /etc/localtime 2>/dev/null) || return 0
    printf '%s' "${tz#*zoneinfo/}"
}

default_router() {  # the default gateway right now (the first install records it as HOME_ROUTER)
    route -n get default 2>/dev/null | awk '/gateway:/ { print $2; exit }' | grep -E '^([0-9]{1,3}\.){3}[0-9]{1,3}$' || true
}

when_ok() {         # "KEY=value" | "KEY!=value" | "KEY?" (set and not empty: an answer or a secret) | ""
    local cond=$1 key val
    [ -n "$cond" ] || return 0
    case "$cond" in
        *'?')    key=${cond%?}; val=$(answer "$key" || secret "$key" || true); [ -n "$val" ] ;;
        *'!='*) key=${cond%%!=*}; val=${cond#*!=}; [ "$(answer "$key")" != "$val" ] ;;
        *=*)    key=${cond%%=*};  val=${cond#*=};  [ "$(answer "$key")" = "$val" ] ;;
        *)      die "bad condition in a prompts file: $cond" ;;
    esac
}

normalize_value() { # validator value -> value as stored (paths absolute, no trailing slash)
    local spec=${1#\?} v=$2
    case "$spec" in
        dir)
            # shellcheck disable=SC2088  # a literal "~" typed by the user, expanded here
            case "$v" in
                '~') v=$HOME ;;
                '~/'*) v="$HOME/${v#\~/}" ;;
            esac
            while [ "${#v}" -gt 1 ] && [ "${v%/}" != "$v" ]; do v=${v%/}; done
            ;;
    esac
    printf '%s' "$v"
}

# ---------------------------------------------------------------- validation

VALID_MSG=''
validate() {        # validator value -> 0 when the value is acceptable; VALID_MSG says why not
    local spec=$1 v=$2 re
    VALID_MSG=''
    case "$spec" in
        '?'*) [ -z "$v" ] && return 0; spec=${spec#\?} ;;
        *) [ -n "$v" ] || { VALID_MSG='a value is required'; return 1; } ;;
    esac
    case "$spec" in
        ''|any)
            return 0 ;;
        choice:*)
            case ",${spec#choice:}," in *",$v,"*) return 0 ;; esac
            VALID_MSG="must be one of: $(printf '%s' "${spec#choice:}" | sed 's/,/, /g')" ;;
        dir)
            re='^/[^[:cntrl:]]*$'
            if [[ $v =~ $re ]] && [ "$v" != / ]; then
                case "/$v/" in */../*|*/./*) ;; *) return 0 ;; esac
            fi
            VALID_MSG='must be a full folder path, like ~/Media or /Volumes/Drive/Media' ;;
        nodename)
            re='^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be lowercase letters, digits and dashes (a Tailscale machine name)' ;;
        tz)
            re='^[A-Za-z0-9_+-]+(/[A-Za-z0-9_+-]+)*$'
            [[ $v =~ $re ]] && [ -f "/usr/share/zoneinfo/$v" ] && return 0
            VALID_MSG='must be a time zone name like America/New_York' ;;
        tskey)
            re='^tskey-auth-[A-Za-z0-9]+-[A-Za-z0-9]+$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be a Tailscale auth key (starts with tskey-auth-)' ;;
        wgkey)
            re='^[A-Za-z0-9+/]{43}=$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be a WireGuard private key (44 characters of base64 ending in =)' ;;
        ipv4)
            re='^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})$'
            if [[ $v =~ $re ]] && [ "${BASH_REMATCH[1]}" -le 255 ] && [ "${BASH_REMATCH[2]}" -le 255 ] \
                && [ "${BASH_REMATCH[3]}" -le 255 ] && [ "${BASH_REMATCH[4]}" -le 255 ]; then
                return 0
            fi
            VALID_MSG='must be an address like 192.168.1.1' ;;
        cidr)
            re='^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}(,([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2})*$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be an address like 10.2.0.2/32' ;;
        hcurl)
            re='^https://hc-ping\.com/([0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}|[A-Za-z0-9_-]{22}/[a-z0-9-]+)$'
            [[ $v =~ $re ]] && return 0
            re='^https?://[A-Za-z0-9.-]+(:[0-9]+)?(/[A-Za-z0-9._-]+)*/ping/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be a Healthchecks ping URL, like https://hc-ping.com/<uuid>' ;;
        ntfy)
            re='^[A-Za-z0-9_-]{1,64}$'
            [[ $v =~ $re ]] && return 0
            re='^https?://[A-Za-z0-9.-]+(:[0-9]+)?/[A-Za-z0-9_-]{1,64}$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be an ntfy topic name, or a URL like https://ntfy.sh/<topic>' ;;
        subnet24)
            re='^([0-9]{1,3})\.([0-9]{1,3})\.([0-9]{1,3})\.0/24$'
            if [[ $v =~ $re ]] && [ "${BASH_REMATCH[1]}" -le 255 ] && [ "${BASH_REMATCH[2]}" -le 255 ] \
                && [ "${BASH_REMATCH[3]}" -le 255 ]; then
                return 0
            fi
            VALID_MSG='must be a /24 network like 172.31.97.0/24' ;;
        countries)
            re='^[A-Za-z][A-Za-z ,.()-]*$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be country names separated by commas, like United States,Canada' ;;
        homarrkey)
            # Homarr shows keys once, as <id>.<token>
            re='^[^[:space:].]+\.[^[:space:]]{16,}$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be a Homarr API key, shown once as <id>.<token>' ;;
        count)
            re='^[1-9][0-9]*$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be a whole number, 1 or more' ;;
        model)
            # An Ollama model, name[:tag] as ollama.com/library lists it, or none
            re='^[a-z0-9][a-z0-9._/-]*(:[A-Za-z0-9._-]+)?$'
            [[ $v =~ $re ]] && return 0
            VALID_MSG='must be an Ollama model such as qwen3.5:9b (ollama.com/library), or none' ;;
        *)
            die "unknown validator in a prompts file: $spec" ;;
    esac
    return 1
}

# ---------------------------------------------------------------- help
#
# A module's help file: KEY|about|where to get it|after|when, one line per key. The first line
# whose when-condition holds wins. "after" marks keys only needed after the first install.

help_field() {      # module key field(2=about 3=get 4=after) -> text
    local hf line about get after when
    hf="$(mod_dir "$1")/help"
    [ -f "$hf" ] || return 1
    while IFS='|' read -r line about get after when <&3; do
        [ "$line" = "$2" ] || continue
        when_ok "$when" || continue
        case "$3" in 2) printf '%s' "$about" ;; 3) printf '%s' "$get" ;; 4) printf '%s' "$after" ;; esac
        return 0
    done 3<"$hf"
    return 1
}

# Help text may hold "\n" for a forced line break (to keep a command on a line of its own).
unescape_nl() { awk '{ gsub(/\\n/, "\n"); print }'; }

wrap() {            # prefix width: wrap stdin, prefixing every line
    unescape_nl | fold -s -w "$2" | sed -e 's/ *$//' -e "s|^|$1|"
}

# ---------------------------------------------------------------- prompts

gen_secret() {      # format -> a new random secret
    local out=''
    case "$1" in
        hex16) out=$(openssl rand -hex 16) ;;
        hex24) out=$(openssl rand -hex 24) ;;
        hex32) out=$(openssl rand -hex 32) ;;
        apikey)
            # 32 hex digits starting with a letter: Bazarr re-reads values that look like
            # numbers (all digits, or 1e5...) as numbers and then drops them
            out=$(openssl rand -hex 16)
            # shellcheck disable=SC2020  # maps each digit to a letter, not a word
            case "$out" in [0-9]*) out=$(printf '%s' "${out:0:1}" | tr '0-9' 'abcdefabcd')${out:1} ;; esac ;;
        alnum24)
            while [ "${#out}" -lt 24 ]; do
                out=$out$(openssl rand -base64 48 | LC_ALL=C tr -dc 'A-Za-z0-9')
            done
            out=$(printf '%s' "$out" | cut -c1-24) ;;
        password24)
            # A login password that passes the usual rules: letters in both cases, a digit and a
            # symbol ("-", which needs no escaping in a URL, JSON or a shell)
            while :; do
                out=$(gen_secret alnum24 | cut -c1-23)
                case "$out" in *[A-Z]*) ;; *) continue ;; esac
                case "$out" in *[a-z]*) ;; *) continue ;; esac
                case "$out" in *[0-9]*) ;; *) continue ;; esac
                break
            done
            out=${out:0:12}-${out:12} ;;
        *) die "unknown secret format: $1" ;;
    esac
    [ -n "$out" ] || die "could not generate a random secret (openssl rand failed)"
    printf '%s' "$out"
}

# Ask for every answer and secret the modules declare that isn't set yet, and generate missing
# app secrets. Answers go to answers.conf as they're given, so an interrupted run keeps them.
# Keys that couldn't be filled (no terminal, no default) are collected in PROMPTS_MISSING.
PROMPTS_MISSING=''
# shellcheck disable=SC2094  # reads the prompts file on fd 3 and writes only the answers/secrets files
run_prompts() {     # modules...
    local m pf file key def spec q when target val shown
    for m in "$@"; do
        pf="$(mod_dir "$m")/prompts"
        [ -f "$pf" ] || continue
        while IFS='|' read -r file key def spec q when <&3; do
            case "$file" in ''|'#'*) continue ;; esac
            when_ok "$when" || continue
            case "$file" in
                gen)
                    secret "$key" >/dev/null && continue
                    kv_append "$GEN_SECRETS" "$key" "$(gen_secret "$def")" quote
                    continue ;;
                answers) target=$ANSWERS ;;
                secrets) target=$SECRETS ;;
                *) die "$(tilde "$pf"): unknown file '$file' for $key" ;;
            esac
            # Set already: done, unless a required key was left empty (a template's KEY="").
            # A new line is appended then, since the last line wins; nothing existing changes.
            if val=$(kv_get "$target" "$key"); then
                [ -n "$val" ] && continue
                validate "$spec" "" && continue
            fi
            [ -n "$q" ] || continue
            def=$(expand_default "$def")
            if ! is_interactive; then
                # No one to ask: record a usable default; leave optional keys unset so a later run
                # in Terminal still asks for them; collect required keys that have no default.
                if [ -n "$def" ] && validate "$spec" "$def"; then
                    kv_append "$target" "$key" "$def" "$([ "$file" = secrets ] && echo quote)" force
                elif ! validate "$spec" ""; then
                    PROMPTS_MISSING=$(list_add "$PROMPTS_MISSING" "$key ($(basename "$(shown "$target")"))")
                fi
                continue
            fi
            shown=$(tilde "$def")
            case "$spec" in '?'*) q="$q (Enter to skip)" ;; esac
            prompt_help "$m" "$key"
            # A list to pick from (the module's choices file): its number or any other value
            CHOICE_DEF=''
            choices_show "$m" "$key" "$def" && [ -n "$CHOICE_DEF" ] && shown=$CHOICE_DEF
            while :; do
                if [ "$file" = secrets ]; then
                    val=$(ask_line "$q" "" silent) || die "input ended before $key was answered"
                else
                    val=$(ask_line "$q" "$shown") || die "input ended before $key was answered"
                    [ "$val" = "$shown" ] && val=$def
                    val=$(choice_value "$m" "$key" "$val")
                fi
                val=$(normalize_value "$spec" "$val")
                validate "$spec" "$val" && break
                warn "$key $VALID_MSG"
            done
            kv_append "$target" "$key" "$val" "$([ "$file" = secrets ] && echo quote)" force
        done 3<"$pf"
    done
}

# A module's choices file: KEY|value|description lines, a list to pick from for that key's
# question, numbered from 1. The suggested one (the question's default) is marked, and its number
# becomes the default shown (CHOICE_DEF). Any other value can still be typed.
CHOICE_DEF=''
choices_lines() {   # module key -> value|description lines
    local f
    f="$(mod_dir "$1")/choices"
    [ -f "$f" ] || return 1
    awk -F'|' -v k="$2" '$1 == k { print $2 "|" $3 }' "$f"
}
choices_show() {    # module key default -> 0 when the key has a list (printed to stderr)
    local lines n=0 val desc mark
    lines=$(choices_lines "$1" "$2") && [ -n "$lines" ] || return 1
    printf '\n' >&2
    while IFS='|' read -r val desc; do
        n=$((n + 1))
        mark=''
        if [ "$val" = "$3" ]; then mark=" ${C_GRN}(suggested for this Mac)${C_OFF}"; CHOICE_DEF=$n; fi
        printf '    %2d  %-13s %s%s\n' "$n" "$val" "$desc" "$mark" >&2
    done <<<"$lines"
    return 0
}
choice_value() {    # module key answer -> the value a list number stands for, else the answer
    local v
    case "$3" in ''|*[!0-9]*) printf '%s' "$3"; return 0 ;; esac
    v=$(choices_lines "$1" "$2" | sed -n "${3}p" | cut -d'|' -f1)
    printf '%s' "${v:-$3}"
}

prompt_help() {     # module key: the key's help, dimmed, above its question
    local about get
    about=$(help_field "$1" "$2" 2) || return 0
    get=$(help_field "$1" "$2" 3 || true)
    printf '\n' >&2
    { printf '%s\n' "$about"; [ -z "$get" ] || printf '%s\n' "$get"; } | wrap "  $C_DIM" 92 | sed "s/\$/$C_OFF/" >&2
}

# Check the format of every value the modules declare. Secrets are never printed.
# Returns 1 when something is wrong.
# shellcheck disable=SC2094  # reads the prompts file on fd 3; writes nothing
check_values() {    # modules...
    local m pf file key def spec q when target val bad=0
    for m in "$@"; do
        pf="$(mod_dir "$m")/prompts"
        [ -f "$pf" ] || continue
        while IFS='|' read -r file key def spec q when <&3; do
            case "$file" in answers) target=$ANSWERS ;; secrets) target=$SECRETS ;; *) continue ;; esac
            when_ok "$when" || continue
            if ! val=$(kv_get "$target" "$key"); then
                [ -n "$q" ] || continue     # never asked: the default applies
                validate "$spec" "" && continue
                err "$key is not set ($(shown "$target"))"
                bad=1
                continue
            fi
            val=$(normalize_value "$spec" "$val")
            if ! validate "$spec" "$val"; then
                err "$key in $(shown "$target") $VALID_MSG"
                bad=1
            fi
        done 3<"$pf"
    done
    return $bad
}

# ---------------------------------------------------------------- version holds
#
# A module's holds file:     <service> <tag> <yyyy-mm> <reason...>
# answers.conf, per machine: HOLD_<service>=<tag> # <reason>, <yyyy-mm>
#                            HOLD_<service>=none   lifts a module's hold
# The answers file wins over the module.

holds_list() {      # modules... -> service|tag|yyyy-mm|reason|source lines
    local m hf svc tag date reason key comment lines=''
    for m in "$@"; do
        hf="$(mod_dir "$m")/holds"
        [ -f "$hf" ] || continue
        while read -r svc tag date reason <&3; do
            case "$svc" in ''|'#'*) continue ;; esac
            lines="$lines$svc|$tag|$date|$reason|$m
"
        done 3<"$hf"
    done
    for key in $(kv_keys "$ANSWERS"); do
        case "$key" in HOLD_?*) ;; *) continue ;; esac
        svc=${key#HOLD_}
        tag=$(kv_get "$ANSWERS" "$key")
        comment=$(kv_comment "$ANSWERS" "$key")
        date=$(printf '%s' "$comment" | sed -nE 's/.*([0-9]{4}-[0-9]{2}).*/\1/p')
        reason=$comment
        if [ -n "$date" ]; then
            reason=$(printf '%s' "$comment" | sed -E "s/[,; ]*${date}[,; ]*/ /; s/^ +//; s/ +$//")
        fi
        lines=$(printf '%s' "$lines" | awk -F'|' -v s="$svc" '$1 != s')
        [ -n "$lines" ] && lines="$lines
"
        lines="$lines$svc|$tag|$date|$reason|answers
"
    done
    printf '%s' "$lines"
}

months_since() {    # yyyy-mm -> whole months until now ("" when the date is malformed)
    local y m ny nm re='^[0-9]{4}-[0-9]{2}$'
    [[ $1 =~ $re ]] || return 0
    y=${1%-*}; m=${1#*-}
    ny=$(date +%Y); nm=$(date +%m)
    printf '%s' $(( (10#$ny * 12 + 10#$nm) - (10#$y * 12 + 10#$m) ))
}
