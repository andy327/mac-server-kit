# shellcheck shell=bash
# The install steps after configuration: folders, PATH, compose projects, seeding, start.
# Sourced by ./kit after modules.sh.

ZPROFILE=$HOME/.zprofile
ZPROFILE_MARK='# added by mac-server-kit'

# ---------------------------------------------------------------- folders and PATH

# A folder on an external drive (/Volumes/<drive>/...) is only used when the drive is mounted.
# Otherwise mkdir would quietly create it on the startup disk, and media would fill that instead.
check_volume() {    # path
    local vol
    case "$1" in
        /Volumes/*/*|/Volumes/*) vol=/Volumes/$(printf '%s' "${1#/Volumes/}" | cut -d/ -f1) ;;
        *) return 0 ;;
    esac
    [ -d "$vol" ] || die "$vol isn't mounted. Connect the drive (or change $1 in $(tilde "$ANSWERS")), then run ./kit install again."
}

layout_create() {
    local media d
    media=$(answer MEDIA_ROOT)
    check_volume "$media"
    for d in bin appdata backups logs kit; do
        mkdir -p "$SERVER_DIR/$d" || die "could not create $SERVER_DIR/$d"
    done
    for d in Downloads Movies 'TV Shows'; do
        mkdir -p "$media/$d" || die "could not create $media/$d"
    done
    ok "Folders: $(tilde "$SERVER_DIR"), $(tilde "$media")"
}

# One marked line in ~/.zprofile puts ~/server/bin on the PATH. Added once; never changed after.
# shellcheck disable=SC2016  # $HOME and $PATH are for zsh to expand, not us
zprofile_line() {
    local bin=$SERVER_DIR/bin
    case "$bin" in "$HOME"/*) bin='$HOME'${bin#"$HOME"} ;; esac
    printf 'export PATH="%s:$PATH"  %s' "$bin" "$ZPROFILE_MARK"
}

zprofile_add() {
    if [ -f "$ZPROFILE" ] && grep -qF "$ZPROFILE_MARK" "$ZPROFILE"; then
        return 0
    fi
    if [ -s "$ZPROFILE" ] && [ -n "$(tail -c 1 "$ZPROFILE")" ]; then printf '\n' >>"$ZPROFILE"; fi
    { zprofile_line; printf "\n"; } >>"$ZPROFILE" || die "could not write $(tilde "$ZPROFILE")"
    ok "Added $(tilde "$SERVER_DIR/bin") to the PATH in $(tilde "$ZPROFILE") (new Terminal windows)"
}

# ---------------------------------------------------------------- compose projects
#
# A module with PROJECT=<p> belongs to project <p>: its compose.yml and env file go there. Any
# module can also add to another enabled project with compose.<p>.yml and env.<p>.
# Each project lives in ~/server/<p>/, its app data in ~/server/appdata/<p>/.

projects_of() {     # modules... -> their projects, in module order
    local m p out=''
    for m in "$@"; do
        p=$(mod_conf "$m" PROJECT)
        [ -n "$p" ] && out=$(list_add "$out" "$p")
    done
    printf '%s' "$out"
}

project_dir() { printf '%s/%s' "$SERVER_DIR" "$1"; }
project_appdata() { printf '%s/appdata/%s' "$SERVER_DIR" "$1"; }

# module project kind(env|compose) -> the module's file for that project, if it has one
module_project_file() {
    local d f
    d=$(mod_dir "$1")
    if [ "$(mod_conf "$1" PROJECT)" = "$2" ]; then
        case "$3" in env) f=$d/env ;; *) f=$d/compose.yml ;; esac
    else
        case "$3" in env) f=$d/env.$2 ;; *) f=$d/compose.$2.yml ;; esac
    fi
    [ -f "$f" ] && printf '%s' "$f"
}

# Fill in ${NAME} references in an env value (see modules/*/env). Values are taken as they are,
# so a value holding "${...}" isn't expanded again.
RENDER_PROJECT=''
render_value() {    # text -> the text with ${NAME} filled in
    local rest=$1 out='' name val re='\$\{([A-Za-z_][A-Za-z0-9_]*)\}'
    while [[ $rest =~ $re ]]; do
        name=${BASH_REMATCH[1]}
        case "$name" in
            KIT_PUID) val=$(id -u) ;;
            KIT_PGID) val=$(id -g) ;;
            KIT_APPDATA) val=$(project_appdata "$RENDER_PROJECT") ;;
            *)
                if val=$(answer "$name"); then
                    :
                elif val=$(secret "$name"); then
                    :
                elif prompt_entry secrets "$name" >/dev/null; then
                    val=''      # an optional secret left out
                else
                    die "\${$name} in an env file isn't an answer, a secret or a kit value"
                fi ;;
        esac
        out=$out${rest%%"\${$name}"*}$val
        rest=${rest#*"\${$name}"}
    done
    printf '%s' "$out$rest"
}

# The project's .env: what Compose reads for ${...} in the compose files, and for COMPOSE_*
# settings when docker compose runs in the project folder. Private, since it holds keys.
ENV_HEADER='# Generated by ./kit install from answers.conf, secrets.conf and kit/generated-secrets.conf.
# Do not edit: it is rewritten on every install. Change answers.conf instead.'

# shellcheck disable=SC2094  # reads the env file on fd 3; only prints its name
env_lines() {       # project modules... -> KEY=value lines (unquoted, in module order)
    local p=$1 m f key val when seen=''
    shift
    RENDER_PROJECT=$p
    for m in "$@"; do
        f=$(module_project_file "$m" "$p" env) || continue
        while IFS='|' read -r key val when <&3; do
            case "$key" in ''|'#'*) continue ;; esac
            when_ok "$when" || continue
            in_list "$key" "$seen" && die "$(tilde "$f"): $key is set twice for $p"
            seen=$(list_add "$seen" "$key")
            val=$(render_value "$val")
            case "$val" in
                *"'"*|*$'\n'*) die "the value for $key (from $(tilde "$f")) can't hold a ' or a line break" ;;
            esac
            printf '%s=%s\n' "$key" "$val"
        done 3<"$f"
    done
}

env_write() {       # project compose-file-list modules...
    local p=$1 files=$2 dir lines
    shift 2
    dir=$(project_dir "$p")
    mkdir -p "$dir" "$(project_appdata "$p")" || die "could not create $dir"
    lines=$(env_lines "$p" "$@") || exit 1
    {
        printf '%s\n' "$ENV_HEADER"
        printf 'COMPOSE_PROJECT_NAME=%s\n' "$p"
        printf 'COMPOSE_FILE=%s\n' "$files"
        printf '%s\n' "$lines" | sed '/^$/d' | sed "s/=\(.*\)$/='\1'/"
    } | write_generated "$dir/.env" 600
}

project_has_files() {   # project modules... -> 0 when some module has an env or compose file for it
    local p=$1 m
    shift
    for m in "$@"; do
        module_project_file "$m" "$p" env >/dev/null && return 0
        module_project_file "$m" "$p" compose >/dev/null && return 0
    done
    return 1
}

# Copy every compose file for the project into ~/server/<p>/compose.d/ (rebuilt each time, so a
# disabled module's file is gone) and print the COMPOSE_FILE list: the files in module order,
# then compose.override.yml if the user made one. Setting COMPOSE_FILE turns off Compose's own
# loading of the override, which is why it's listed.
compose_assemble() {    # project modules... -> the COMPOSE_FILE value
    local p=$1 dir new m f n=10 list=''
    shift
    dir=$(project_dir "$p")
    new=$dir/.compose.d.new
    { rm -rf "$new" && mkdir -p "$new"; } || die "could not create $new"
    for m in "$@"; do
        f=$(module_project_file "$m" "$p" compose) || continue
        cp "$f" "$new/$n-$m.yml" || die "could not copy $f"
        list="${list:+$list:}compose.d/$n-$m.yml"
        n=$((n + 1))
    done
    { rm -rf "$dir/compose.d" && mv "$new" "$dir/compose.d"; } || die "could not replace $dir/compose.d"
    [ -f "$dir/compose.override.yml" ] && list="$list:compose.override.yml"
    printf '%s' "$list"
}

# The services and images in one of the kit's compose files, read without a YAML parser. Works
# because the kit's compose files follow fixed layout rules (see modules/media-stack/compose.yml;
# test-project.sh checks every module's files).
compose_images() {      # file -> "service image" lines
    awk '
        /^[^ #]/ { top = $0; svc = ""; next }
        top == "services:" && /^  [a-z0-9][a-z0-9_-]*:[ \t]*$/ { svc = $1; sub(/:$/, "", svc); next }
        svc != "" && /^    image:/ { img = $0; sub(/^    image:[ \t]*/, "", img); sub(/[ \t]+#.*$/, "", img); print svc, img }
    ' "$1"
}

generate_projects() {   # modules... (enabled, in dependency order)
    local p files
    for p in $(projects_of "$@"); do
        project_has_files "$p" "$@" || continue
        mkdir -p "$(project_dir "$p")" || die "could not create $(project_dir "$p")"
        files=$(compose_assemble "$p" "$@") || exit 1
        env_write "$p" "$files" "$@"
        ok "$p: $(tilde "$(project_dir "$p")")"
    done
}
