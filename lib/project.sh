# shellcheck shell=bash
# The install steps after configuration: folders, PATH, compose projects, seeding, start.
# Sourced by ./kit after modules.sh.

ZPROFILE=$HOME/.zprofile
ZPROFILE_MARK='# added by mac-server-kit'

# ---------------------------------------------------------------- folders and PATH

# A folder on an external drive (/Volumes/<drive>/...) is only used when the drive is mounted.
# Otherwise mkdir would quietly create it on the startup disk, and media would fill that instead.
check_volume() {    # path
    local vol
    case "$1" in
        /Volumes/*/*|/Volumes/*) vol=/Volumes/$(printf '%s' "${1#/Volumes/}" | cut -d/ -f1) ;;
        *) return 0 ;;
    esac
    [ -d "$vol" ] || die "$vol isn't mounted. Connect the drive (or change $1 in $(shown "$ANSWERS")), then run ./kit install again."
}

layout_create() {
    local media d
    media=$(answer MEDIA_ROOT)
    check_volume "$media"
    for d in bin appdata backups logs kit; do
        mkdir -p "$SERVER_DIR/$d" || die "could not create $SERVER_DIR/$d"
    done
    # Downloads/complete and incomplete are qBittorrent's (hooks/seed); made now, Sonarr and Radarr
    # warn about a missing download folder until the first download would make it
    for d in Downloads/complete Downloads/incomplete Movies 'TV Shows'; do
        mkdir -p "$media/$d" || die "could not create $media/$d"
    done
    ok "Folders: $(tilde "$SERVER_DIR"), $(tilde "$media")"
}

# One marked line in ~/.zprofile puts ~/server/bin on the PATH. Added once; never changed after.
# shellcheck disable=SC2016  # $HOME and $PATH are for zsh to expand, not us
zprofile_line() {
    local bin=$SERVER_DIR/bin
    case "$bin" in "$HOME"/*) bin='$HOME'${bin#"$HOME"} ;; esac
    printf 'export PATH="%s:$PATH"  %s' "$bin" "$ZPROFILE_MARK"
}

zprofile_add() {
    if [ -f "$ZPROFILE" ] && grep -qF "$ZPROFILE_MARK" "$ZPROFILE"; then
        return 0
    fi
    if [ -s "$ZPROFILE" ] && [ -n "$(tail -c 1 "$ZPROFILE")" ]; then printf '\n' >>"$ZPROFILE"; fi
    { zprofile_line; printf "\n"; } >>"$ZPROFILE" || die "could not write $(tilde "$ZPROFILE")"
    ok "Added $(tilde "$SERVER_DIR/bin") to the PATH in $(tilde "$ZPROFILE") (new Terminal windows)"
}

# ---------------------------------------------------------------- compose projects
#
# A module with PROJECT=<p> belongs to project <p>: its compose.yml and env file go there. Any
# module can also add to another enabled project with compose.<p>.yml and env.<p>.
# Each project lives in ~/server/<p>/, its app data in ~/server/appdata/<p>/.

projects_of() {     # modules... -> their projects, in module order
    local m p out=''
    for m in "$@"; do
        p=$(mod_conf "$m" PROJECT)
        [ -n "$p" ] && out=$(list_add "$out" "$p")
    done
    printf '%s' "$out"
}

project_dir() { printf '%s/%s' "$SERVER_DIR" "$1"; }
project_appdata() { printf '%s/appdata/%s' "$SERVER_DIR" "$1"; }

# module project kind(env|serve|compose) -> the module's file for that project, if it has one
module_project_file() {
    local d f
    d=$(mod_dir "$1")
    if [ "$(mod_conf "$1" PROJECT)" = "$2" ]; then
        case "$3" in env|serve) f=$d/$3 ;; *) f=$d/compose.yml ;; esac
    else
        case "$3" in env|serve) f=$d/$3.$2 ;; *) f=$d/compose.$2.yml ;; esac
    fi
    [ -f "$f" ] && printf '%s' "$f"
}

# Fill in ${NAME} references in an env value (see modules/*/env). Values are taken as they are,
# so a value holding "${...}" isn't expanded again.
RENDER_PROJECT=''
render_value() {    # text -> the text with ${NAME} filled in
    local rest=$1 out='' name val re='\$\{([A-Za-z_][A-Za-z0-9_]*)\}'
    while [[ $rest =~ $re ]]; do
        name=${BASH_REMATCH[1]}
        case "$name" in
            KIT_PUID) val=$(id -u) ;;
            KIT_PGID) val=$(id -g) ;;
            KIT_APPDATA) val=$(project_appdata "$RENDER_PROJECT") ;;
            KIT_LOGS) val=$SERVER_DIR/logs ;;
            *)
                if val=$(answer "$name"); then
                    :
                elif val=$(secret "$name"); then
                    :
                elif prompt_entry secrets "$name" >/dev/null; then
                    val=''      # an optional secret left out
                else
                    die "\${$name} in an env file isn't an answer, a secret or a kit value"
                fi ;;
        esac
        out=$out${rest%%"\${$name}"*}$val
        rest=${rest#*"\${$name}"}
    done
    printf '%s' "$out$rest"
}

# The project's .env: what Compose reads for ${...} in the compose files, and for COMPOSE_*
# settings when docker compose runs in the project folder. Private, since it holds keys.
ENV_HEADER='# Generated by ./kit install from answers.conf, secrets.conf and kit/generated-secrets.conf.
# Do not edit: it is rewritten on every install. Change answers.conf instead.'

# shellcheck disable=SC2094  # reads the env file on fd 3; only prints its name
env_lines() {       # project modules... -> KEY=value lines (unquoted, in module order)
    local p=$1 m f key val when seen=''
    shift
    # shellcheck disable=SC2034  # when_ok reads WHEN_PROJECT
    RENDER_PROJECT=$p WHEN_PROJECT=$p
    for m in "$@"; do
        f=$(module_project_file "$m" "$p" env) || continue
        while IFS='|' read -r key val when <&3; do
            case "$key" in ''|'#'*) continue ;; esac
            when_ok "$when" || continue
            in_list "$key" "$seen" && die "$(tilde "$f"): $key is set twice for $p"
            seen=$(list_add "$seen" "$key")
            val=$(render_value "$val")
            case "$val" in
                *"'"*|*$'\n'*) die "the value for $key (from $(tilde "$f")) can't hold a ' or a line break" ;;
            esac
            printf '%s=%s\n' "$key" "$val"
        done 3<"$f"
    done
}

env_write() {       # project compose-file-list modules...
    local p=$1 files=$2 dir lines
    shift 2
    dir=$(project_dir "$p")
    mkdir -p "$dir" "$(project_appdata "$p")" || die "could not create $dir"
    lines=$(env_lines "$p" "$@") || exit 1
    {
        printf '%s\n' "$ENV_HEADER"
        printf 'COMPOSE_PROJECT_NAME=%s\n' "$p"
        printf 'COMPOSE_FILE=%s\n' "$files"
        printf '%s\n' "$lines" | sed '/^$/d' | sed "s/=\(.*\)$/='\1'/"
    } | write_generated "$dir/.env" 600
}

project_has_files() {   # project modules... -> 0 when some module has an env or compose file for it
    local p=$1 m
    shift
    for m in "$@"; do
        module_project_file "$m" "$p" env >/dev/null && return 0
        module_project_file "$m" "$p" compose >/dev/null && return 0
    done
    return 1
}

# Copy every module compose file for the project into ~/server/<p>/compose.d/ (rebuilt each
# time, so a disabled module's file is gone) and print their COMPOSE_FILE entries, in module
# order. generate_projects adds the image pins and the user's override after them.
compose_assemble() {    # project modules... -> compose.d/... entries, ":"-separated
    local p=$1 dir new m f n=10 list=''
    shift
    dir=$(project_dir "$p")
    new=$dir/.compose.d.new
    { rm -rf "$new" && mkdir -p "$new"; } || die "could not create $new"
    for m in "$@"; do
        f=$(module_project_file "$m" "$p" compose) || continue
        cp "$f" "$new/$n-$m.yml" || die "could not copy $f"
        list="${list:+$list:}compose.d/$n-$m.yml"
        n=$((n + 1))
    done
    { rm -rf "$dir/compose.d" && mv "$new" "$dir/compose.d"; } || die "could not replace $dir/compose.d"
    printf '%s' "$list"
}

# The services and images in one of the kit's compose files, read without a YAML parser. Works
# because the kit's compose files follow fixed layout rules (see modules/media-stack/compose.yml;
# test-project.sh checks every module's files).
compose_images() {      # file -> "service image" lines
    awk '
        /^[^ #]/ { top = $0; svc = ""; next }
        top == "services:" && /^  [a-z0-9][a-z0-9_-]*:[ \t]*$/ { svc = $1; sub(/:$/, "", svc); next }
        svc != "" && /^    image:/ { img = $0; sub(/^    image:[ \t]*/, "", img); sub(/[ \t]+#.*$/, "", img); print svc, img }
    ' "$1"
}

# ---------------------------------------------------------------- image pins
#
# ~/server/<p>/images.lock holds one pin per service: "service repo:tag@sha256:... [track]". The
# install pins services that have no pin yet (pulling the tracked tag) and never moves an existing
# pin; update-all refreshes them. The tracked tag is the compose file's, or a version hold's. A
# hold can name a release series (v2.*): the pin is then the newest matching release, and track
# records the series for update-all (modules/core/bin/kit-registry.sh finds the release).
# zz-images.yml applies the pins through Compose's own merge, so the repo's compose files never
# change.

LOCK_HEADER='# Image pins for this project: service repo:tag@digest. Kept by ./kit install (new
# services) and update-all (refreshes). Delete a line to have the next install pin it afresh.'

hold_tag() {        # service modules... -> the held tag ("" when not held, or the hold is lifted)
    local svc=$1 tag
    shift
    tag=$(holds_list "$@" | awk -F'|' -v s="$svc" '$1 == s { t = $2 } END { print t }')
    [ "$tag" = none ] && tag=''
    printf '%s' "$tag"
}

image_digest() {    # repo:tag (pulled) -> sha256:...
    local ref=$1 line
    line=$(dk image inspect --format '{{range .RepoDigests}}{{println .}}{{end}}' "$ref" 2>/dev/null \
        | awk -v r="${ref%:*}@" 'NF { if (index($0, r) == 1) { print; f = 1; exit } if (!first) first = $0 }
                                  END { if (!f && first) print first }')
    case "$line" in *@sha256:*) printf '%s' "${line#*@}" ;; *) return 1 ;; esac
}

lock_get() { [ -f "$1" ] && awk -v s="$2" '$1 == s { p = $2 } END { if (p == "") exit 1; print p }' "$1"; }

lock_track() { [ -f "$1" ] && awk -v s="$2" '$1 == s { t = $3 } END { print t }' "$1"; }

lock_set() {        # lock service pin [track]
    local lock=$1 tmp
    tmp=$(mktemp "$(dirname "$lock")/.kit.XXXXXX") || die "could not write $lock"
    awk -v s="$2" -v p="$3" -v t="${4:-}" '
        function line() { return s " " p (t != "" ? " " t : "") }
        $1 == s { if (!d) print line(); d = 1; next } { print } END { if (!d) print line() }' \
        "$lock" >"$tmp" || { rm -f "$tmp"; die "could not write $lock"; }
    mv -f "$tmp" "$lock" || { rm -f "$tmp"; die "could not write $lock"; }
}

# Pin what's missing, then write compose.d/zz-images.yml for this project's services.
images_pin() {      # project modules...
    local p=$1 dir lock f svc img repo tag pin ref held track services='' zz
    shift
    dir=$(project_dir "$p")
    lock=$dir/images.lock
    [ -f "$lock" ] || printf '%s\n' "$LOCK_HEADER" >"$lock" || die "could not create $lock"
    for f in "$dir"/compose.d/[0-9]*.yml; do
        [ -f "$f" ] || continue
        while read -r svc img; do
            [ -n "$svc" ] || continue
            repo=${img%:*}
            tag=${img##*:}
            held=$(hold_tag "$svc" "$@")
            [ -n "$held" ] && tag=$held
            track=''
            case "$tag" in *'*'*) track=$tag ;; esac
            services=$(list_add "$services" "$svc")
            if pin=$(lock_get "$lock" "$svc"); then
                ref=${pin%%@*}
                if [ "${ref%:*}" = "$repo" ]; then
                    # Pinned already (a new repo is pinned afresh); keep what it tracks current
                    [ "$(lock_track "$lock" "$svc")" = "$track" ] || lock_set "$lock" "$svc" "$pin" "$track"
                    continue
                fi
            fi
            if [ -n "$track" ]; then
                tag=$(newest_tag "$repo" "$track")
                [ -n "$tag" ] || die "could not find a release of $repo matching $track (is this Mac online?)"
            fi
            info "Pulling $repo:$tag for $svc"
            dk pull -q "$repo:$tag" >/dev/null || die "could not pull $repo:$tag (is this Mac online?)"
            pin=$(image_digest "$repo:$tag") || die "could not read the digest of $repo:$tag"
            lock_set "$lock" "$svc" "$repo:$tag@$pin" "$track"
            ok "Pinned $svc: $repo:$tag ($(printf '%s' "$pin" | cut -c1-19)...)"
        done <<EOF2
$(compose_images "$f")
EOF2
    done
    zz=$dir/compose.d/zz-images.yml
    {
        echo "# Generated by ./kit install from images.lock. Do not edit."
        echo "services:"
        for svc in $services; do
            pin=$(lock_get "$lock" "$svc") || continue
            printf '  %s:\n    image: %s\n' "$svc" "$pin"
            in_list wud "$*" && wud_labels "${pin%%@*}" "$(lock_track "$lock" "$svc")"
        done
    } | write_generated "$zz"
}

# With the wud module, labels that keep What's Up Docker to what update-all would pull: newer
# images of the same tag, or for a release series (v2.*), its newer releases (as newest_tag
# matches them). $$ is a literal $ in a compose file.
wud_labels() {      # repo:tag track
    local re
    if [ -n "$2" ]; then
        re="^$(printf '%s' "${2%\*}" | regex_quote)\\d+(\\.\\d+)*\$\$"
        printf "    labels:\n      - 'wud.tag.include=%s'\n" "$re"
    else
        re="^$(printf '%s' "${1##*:}" | regex_quote)\$\$"
        printf "    labels:\n      - 'wud.tag.include=%s'\n      - wud.watch.digest=true\n" "$re"
    fi
}
regex_quote() { sed 's/[].[^$*+?(){}|\\]/\\&/g'; }

PROJECT_YML_HEADER='# Generated by ./kit install. Do not edit. Listed first in COMPOSE_FILE so that ./ in the
# compose files (and in compose.override.yml) means this folder, not compose.d/.'

generate_projects() {   # modules... (enabled, in dependency order)
    local p dir files
    for p in $(projects_of "$@"); do
        project_has_files "$p" "$@" || continue
        dir=$(project_dir "$p")
        mkdir -p "$dir" || die "could not create $dir"
        files=$(compose_assemble "$p" "$@") || exit 1
        if [ -n "$files" ]; then
            images_pin "$p" "$@"
            # First in the list: Compose takes ./ in every file to mean the first file's folder
            printf '%s\n' "$PROJECT_YML_HEADER" "name: $p" | write_generated "$dir/project.yml"
            files="project.yml:$files:compose.d/zz-images.yml"
        fi
        [ -f "$dir/compose.override.yml" ] && files="${files:+$files:}compose.override.yml"
        env_write "$p" "$files" "$@"
        serve_write "$p" "$@"
        ok "$p: $(tilde "$dir")"
    done
}

# ---------------------------------------------------------------- module hooks and seeding
#
# A module's hooks/<step> file is bash, sourced in a subshell so its variables and functions
# stay its own. It can use everything in lib/ (answer, secret, project_appdata, ok, ...) plus
# the seed helpers below. HOOK_MODULE is the module's name.

has_hooks() {       # step modules... -> 0 when any of them has that hook
    local step=$1 m
    shift
    for m in "$@"; do [ -f "$(mod_dir "$m")/hooks/$step" ] && return 0; done
    return 1
}

run_hooks() {       # step modules...
    local step=$1 m f
    shift
    for m in "$@"; do
        f="$(mod_dir "$m")/hooks/$step"
        [ -f "$f" ] || continue
        # shellcheck disable=SC1090  # module hooks are found at runtime
        # shellcheck disable=SC2034  # HOOK_MODULE is for the hook
        ( HOOK_MODULE=$m; . "$f" ) || die "the $step step for $m failed"
    done
}

# Write a file from stdin only if it doesn't exist yet (seeded files are never overwritten).
seed_file() {       # path [mode]
    local f=$1
    if [ -e "$f" ]; then
        cat >/dev/null
        note "Kept $(tilde "$f") (already there)"
        return 0
    fi
    mkdir -p "$(dirname "$f")" || die "could not create $(dirname "$f")"
    write_generated "$f" "${2:-600}"
    ok "Seeded $(tilde "$f")"
}

xml_value() {       # file tag -> the first <tag>value</tag> in the file
    sed -n "s|.*<$2>\\([^<]*\\)</$2>.*|\\1|p" "$1" 2>/dev/null | head -n 1
}

# PBKDF2-HMAC-SHA512 with the perl that ships with macOS (Digest::SHA is a core module).
pbkdf2_sha512() {   # password salt-hex iterations -> 64-byte key, hex
    PBKDF2_PW=$1 /usr/bin/perl -MDigest::SHA=hmac_sha512 -e '
        my ($salt, $c) = (pack("H*", $ARGV[0]), $ARGV[1]); my $pw = $ENV{PBKDF2_PW};
        my $u = hmac_sha512($salt . pack("N", 1), $pw); my $t = $u;
        for (2 .. $c) { $u = hmac_sha512($u, $pw); $t ^= $u }
        print unpack("H*", $t)' "$2" "$3"
}

hex_to_base64() { /usr/bin/perl -MMIME::Base64 -e 'print encode_base64(pack("H*", $ARGV[0]), "")' "$1"; }

# ---------------------------------------------------------------- start and report

STARTED_PROJECTS=''

# Start (or update) each project: Compose recreates only what changed, removes containers of
# services no longer listed (a disabled module's), and waits until everything is running and
# every health check passes.
start_projects() {  # modules...
    local p dir hint
    STARTED_PROJECTS=''
    for p in $(projects_of "$@"); do
        dir=$(project_dir "$p")
        [ -d "$dir/compose.d" ] && [ -f "$dir/compose.d/zz-images.yml" ] || continue
        info "Starting $p (the first start can take a few minutes)"
        if ! (cd "$dir" && dk compose up -d --wait --wait-timeout 300 --remove-orphans); then
            (cd "$dir" && dk compose ps -a) >&2 || true
            err "$p didn't start cleanly (above)"
            start_hints "$p" "$@" | while IFS= read -r hint; do note "    $hint"; done
            note "    A service's log: cd $(tilde "$dir") && docker compose logs <service>"
            die "$p didn't start; fix the above, then run ./kit install again"
        fi
        STARTED_PROJECTS=$(list_add "$STARTED_PROJECTS" "$p")
        ok "$p is running"
    done
}

# For a wire hook that has just written a mark an env line depends on (@kit-admin, say): the
# project's .env again, and when it changed, up -d (Compose recreates only the services whose
# settings changed). 1 when the restart failed (it warns).
project_refresh() { # project
    local p=$1 dir old files
    dir=$(project_dir "$p")
    [ -f "$dir/.env" ] || return 0
    old=$(cat "$dir/.env")
    files=$(sed -n 's/^COMPOSE_FILE=//p' "$dir/.env")
    # shellcheck disable=SC2086  # ENABLED is a word list
    env_write "$p" "$files" $ENABLED
    [ "$(cat "$dir/.env")" != "$old" ] || return 0
    info "Restarting $p with its new settings"
    run_record restart "$p"
    if ! (cd "$dir" && dk compose up -d --wait --wait-timeout 300); then
        warn "$p didn't restart cleanly (cd $(tilde "$dir") && docker compose ps); run ./kit install again"
        return 1
    fi
    return 0
}

# A module's hints file: service|text, shown when that service doesn't come up. Only the hints of
# services that aren't running and healthy are shown (all of them when compose can't say).
start_hints() {     # project modules... -> hint lines
    local p=$1 m f svc text states
    shift
    states=$(cd "$(project_dir "$p")" && dk compose ps -a --format '{{.Service}}|{{.State}}|{{.Health}}' 2>/dev/null || true)
    for m in "$@"; do
        [ "$(mod_conf "$m" PROJECT)" = "$p" ] || continue
        f="$(mod_dir "$m")/hints"
        [ -f "$f" ] || continue
        while IFS='|' read -r svc text <&3; do
            case "$svc" in ''|'#'*) continue ;; esac
            if [ -n "$states" ] && printf '%s\n' "$states" | grep -qE "^$svc\|running\|(healthy)?\$"; then
                continue
            fi
            printf '%s\n' "$text"
        done 3<"$f"
    done
}

# Whether the install sets anything up for a module yet: a base module, or one with compose files
# or hooks. Its after-install checklist items wait until then (Plex's sign-in, say).
module_installs() {
    local d
    [ "$(mod_conf "$1" KIND)" = base ] && return 0
    d=$(mod_dir "$1")
    [ -d "$d/hooks" ] && return 0
    ls "$d"/compose*.yml >/dev/null 2>&1
}

# A module's urls file: name|url|node:port|when|note, one per app it serves. The Tailscale
# address (node:port) is shown when the node is up, with this Mac's address under it.
OPEN_COUNT=0
report_install() {  # modules... (sets OPEN_COUNT and TODO_COUNT for run_summary)
    local m f name url ts when text tsurl notes
    OPEN_COUNT=0
    section "Open"
    for m in "$@"; do
        f="$(mod_dir "$m")/urls"
        [ -f "$f" ] || continue
        # a native app's (no project) always; a project's once it's running
        [ -z "$(mod_conf "$m" PROJECT)" ] || in_list "$(mod_conf "$m" PROJECT)" "$STARTED_PROJECTS" || continue
        while IFS='|' read -r name url ts when text <&3; do
            case "$name" in ''|'#'*) continue ;; esac
            when_ok "$when" || continue
            tsurl=''
            [ -z "$ts" ] || tsurl=$(ts_url "${ts%%:*}" "${ts#*:}")
            OPEN_COUNT=$((OPEN_COUNT + 1))
            if [ -n "$tsurl" ]; then
                printf '  %s%-14s%s %s%s%s\n' "$C_BLD" "$name" "$C_OFF" "$C_UL" "$tsurl" "$C_OFF"
                printf '                   %sthis Mac: %s%s\n' "$C_DIM" "$url" "$C_OFF"
            else
                printf '  %s%-14s%s %s%s%s\n' "$C_BLD" "$name" "$C_OFF" "$C_UL" "$url" "$C_OFF"
            fi
            [ -z "$text" ] || printf '%s\n' "$text" | wrap "                   $C_DIM" 74 | sed "s/\$/$C_OFF/"
        done 3<"$f"
    done
    printf '\n  %sEvery app'"'"'s sign-in and password: show-logins%s\n' "$C_DIM" "$C_OFF"
    # Notes only for the modules this run added (all of them on a first install); ./kit prepare
    # lists every one
    notes=$(for m in "$@"; do
        in_list "$m" "${PREV_ENABLED:-}" || { module_installs "$m" && ready_items note "$m"; }
    done)
    if [ -n "$notes" ]; then
        section "Good to know"
        printf '%s\n' "$notes" | while IFS= read -r item; do bullet "$item"; done
    fi
    todo_report "$@"
}

# The ready files' to-dos the kit hasn't seen done (sets TODO_COUNT). ./kit install and status.
TODO_COUNT=0
todo_report() {     # modules...
    local todo
    section "Still to do"
    todo=$(for m in "$@"; do module_installs "$m" && ready_items after "$m"; done)
    TODO_COUNT=0
    if [ -z "$todo" ]; then
        ok_again "Nothing: the kit sees every step it can check done"
        return 0
    fi
    TODO_COUNT=$(printf '%s\n' "$todo" | grep -c .)
    printf '%s\n' "$todo" | while IFS= read -r item; do bullet "$item"; done
}

# The last thing an install prints: how long it took, what it made or changed (the wiring's ✓
# lines; at most 5 shown), what restarted, every warning again (they're easy to miss above), and
# how much the Open and Still to do lists hold.
run_summary() {     # (KIT_RUN_LOG, SECONDS since the start, OPEN_COUNT, TODO_COUNT)
    local log=${KIT_RUN_LOG:-/dev/null} new warns restarts n w r t head line
    new=$(sed -n 's/^new|//p' "$log" 2>/dev/null)
    warns=$(sed -n 's/^warn|//p' "$log" 2>/dev/null)
    restarts=$(sed -n 's/^restart|//p' "$log" 2>/dev/null | awk '!s[$0]++' | paste -sd' ' -)
    n=0 w=0 r=0
    [ -z "$new" ] || n=$(printf '%s\n' "$new" | grep -c .)
    [ -z "$warns" ] || w=$(printf '%s\n' "$warns" | grep -c .)
    [ -z "$restarts" ] || r=$(printf '%s\n' "$restarts" | wc -w | tr -d ' ')
    t=$SECONDS
    head="${C_BLD}Done in $((t / 60)):$(printf '%02d' $((t % 60)))${C_OFF}"
    if [ "$n" -eq 0 ]; then head="$head · nothing new"; else head="$head · $n new"; fi
    [ "$r" -eq 0 ] || head="$head · $r restarted"
    if [ "$w" -eq 0 ]; then
        head="$head · ${C_GRN}no warnings${C_OFF}"
    elif [ "$w" -eq 1 ]; then
        head="$head · ${C_YEL}1 warning${C_OFF}"
    else
        head="$head · ${C_YEL}$w warnings${C_OFF}"
    fi
    printf '\n%s╭%s %s\n' "$C_DIM" "$C_OFF" "$head"
    if [ "$n" -gt 0 ]; then
        printf '%s\n' "$new" | head -n 5 | while IFS= read -r line; do
            printf '%s│%s %s✓%s %s\n' "$C_DIM" "$C_OFF" "$C_GRN" "$C_OFF" "$line"
        done
        [ "$n" -le 5 ] || printf '%s│   and %s more (above)%s\n' "$C_DIM" $((n - 5)) "$C_OFF"
    fi
    [ "$r" -eq 0 ] || printf '%s│%s Restarted with new settings: %s\n' "$C_DIM" "$C_OFF" "$restarts"
    if [ "$w" -gt 0 ]; then
        printf '%s\n' "$warns" | while IFS= read -r line; do
            printf '%s\n' "$line" | fold -s -w 84 | sed 's/ *$//' |
                awk -v d="$C_DIM" -v o="$C_OFF" -v y="$C_YEL" \
                    'NR == 1 { print d "│" o " " y "!" o " " $0; next } { print d "│" o "   " $0 }'
        done
    fi
    if [ "$TODO_COUNT" -eq 0 ]; then line='nothing left to do'; else line="$TODO_COUNT still to do (above)"; fi
    printf '%s╰%s %s apps to open · %s\n' "$C_DIM" "$C_OFF" "$OPEN_COUNT" "$line"
}
