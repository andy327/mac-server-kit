# shellcheck shell=bash
# What runs after the install: the runtime scripts in ~/server/bin, ~/server/kit/runtime.conf
# (what those scripts check and where they report), and the kit's launchd jobs. Sourced by ./kit.
#
# A module's bin/ folder holds its runtime scripts; the install copies them into ~/server/bin
# each run and removes the ones no enabled module has any more (~/server/kit/bin.list says which
# are the kit's, so the user's own scripts in ~/server/bin are left alone).
#
# A module's jobs file declares its launchd jobs:
#   name|schedule|command [args]|when
#     name       the job is io.github.andy327.mac-server-kit.<name>
#     schedule   seconds between runs (it also runs when loaded), or weekly:<day>:<HH>:<MM> for
#                once a week at that time (day 0 is Sunday; it doesn't run when loaded, and a
#                run missed while the Mac was asleep happens when it wakes), or always: a native
#                app's runner, started at login and started again if it crashes (a normal quit,
#                exit 0, leaves it stopped), or login: once at login (and when the install
#                loads it)
#     command    a script in ~/server/bin, with its arguments (split on spaces)
#     when       optional condition, as in prompts files
# Each job's plist is generated into ~/Library/LaunchAgents (the only place launchd loads a
# user's jobs from at login) and its output goes to ~/server/logs/<name>.log. A job no enabled
# module declares any more is unloaded and its plist removed.

KIT_JOB_PREFIX=io.github.andy327.mac-server-kit
BIN_LIST=$KIT_STATE/bin.list
RUNTIME_CONF=$KIT_STATE/runtime.conf

klaunchctl() { "${KIT_LAUNCHCTL:-launchctl}" "$@"; }
launch_agents() { printf '%s' "${KIT_LAUNCH_AGENTS:-$HOME/Library/LaunchAgents}"; }

# ---------------------------------------------------------------- scripts

bin_install() {     # modules...
    local m f name new='' old n=0 tmp
    if in_plan; then
        bin_plan "$@"
        return 0
    fi
    for m in "$@"; do
        for f in "$(mod_dir "$m")"/bin/*; do
            [ -f "$f" ] || continue
            name=$(basename "$f")
            in_list "$name" "$new" && die "two modules have a runtime script named $name"
            tmp=$(mktemp "$SERVER_DIR/bin/.kit.XXXXXX") || die "could not write $SERVER_DIR/bin/$name"
            if ! { cp "$f" "$tmp" && chmod 755 "$tmp" && mv -f "$tmp" "$SERVER_DIR/bin/$name"; }; then
                rm -f "$tmp"
                die "could not write $SERVER_DIR/bin/$name"
            fi
            new=$(list_add "$new" "$name")
            n=$((n + 1))
        done
    done
    if [ -f "$BIN_LIST" ]; then
        while IFS= read -r old; do
            case "$old" in ''|'#'*) continue ;; esac
            in_list "$old" "$new" || rm -f "$SERVER_DIR/bin/$old"
        done <"$BIN_LIST"
    fi
    { printf '# Generated by ./kit install: the runtime scripts it put in ~/server/bin. Do not edit.\n'
      for name in $new; do printf '%s\n' "$name"; done; } | write_generated "$BIN_LIST"
    [ $n -eq 0 ] || ok "Runtime scripts in $(tilde "$SERVER_DIR/bin"): $new"
}

# A plan's list of what bin_install would add, update and remove
bin_plan() {        # modules...
    local m f name new='' added='' changed='' old gone=''
    for m in "$@"; do
        for f in "$(mod_dir "$m")"/bin/*; do
            [ -f "$f" ] || continue
            name=$(basename "$f")
            new=$(list_add "$new" "$name")
            if [ ! -f "$SERVER_DIR/bin/$name" ]; then added=$(list_add "$added" "$name")
            elif ! cmp -s "$f" "$SERVER_DIR/bin/$name"; then changed=$(list_add "$changed" "$name"); fi
        done
    done
    if [ -f "$BIN_LIST" ]; then
        while IFS= read -r old; do
            case "$old" in ''|'#'*) continue ;; esac
            in_list "$old" "$new" || gone=$(list_add "$gone" "$old")
        done <"$BIN_LIST"
    fi
    [ -z "$added" ] || plan_add "Runtime scripts to add to $(tilde "$SERVER_DIR/bin"): $added"
    [ -z "$changed" ] || plan_add "Runtime scripts to update: $changed"
    [ -z "$gone" ] || plan_add "Runtime scripts to remove (no enabled module has them): $gone"
    [ -n "$added$changed$gone" ] || note "Runtime scripts: up to date"
}

# ---------------------------------------------------------------- runtime.conf

rt_quote() { printf "'%s'" "${1//\'/\'\\\'\'}"; }

ntfy_url() {        # topic or URL -> the URL to post to
    case "$1" in
        '') ;;
        http://*|https://*) printf '%s' "$1" ;;
        *) printf 'https://ntfy.sh/%s' "$1" ;;
    esac
}

# The folders a project's containers mount from its env lines that use ${KIT_REAL_<answer>}
# (MEDIA_ROOT for the media stack, GAMES_ROOT for RomM), with symlinks followed: one per line
project_folders() { # project modules...
    local p=$1 m f key
    shift
    for m in "$@"; do
        f=$(module_project_file "$m" "$p" env) || continue
        # shellcheck disable=SC2013  # answer names, one word each
        for key in $(grep -o 'KIT_REAL_[A-Z0-9_]*' "$f" | sed 's/^KIT_REAL_//' | sort -u); do
            resolve_path "$(answer "$key")"
            printf '\n'
        done
    done
}

project_volumes() { # project modules... -> the drives (/Volumes/<name>) its folders are on, "|"-separated
    local f vol out=''
    while IFS= read -r f; do
        vol=$(volume_of "$f")
        [ -n "$vol" ] || continue
        case "|$out|" in *"|$vol|"*) ;; *) out=${out:+$out|}$vol ;; esac
    done <<EOF
$(project_folders "$@")
EOF
    printf '%s' "$out"
}

runtime_write() {   # modules...
    local m p projects='' ordered='' native line key val
    for p in $(projects_of "$@"); do
        project_has_files "$p" "$@" && projects=$(list_add "$projects" "$p")
    done
    # shellcheck disable=SC2046  # module names have no spaces
    for p in $(projects_of $(by_backup_order "$@")); do
        in_list "$p" "$projects" && ordered=$(list_add "$ordered" "$p")
    done
    {
        printf '# Generated by ./kit install: what the runtime scripts in ~/server/bin check and where\n'
        printf '# they report. Do not edit; change answers.conf or secrets.conf and run ./kit install.\n'
        printf 'PROJECTS=%s\n' "$(rt_quote "$projects")"
        printf 'JOB_PREFIX=%s\n' "$(rt_quote "$KIT_JOB_PREFIX.")"
        printf 'HEALTHCHECK_URL=%s\n' "$(rt_quote "$(secret HEALTHCHECK_URL || true)")"
        printf 'HEALTHCHECK_API_KEY=%s\n' "$(rt_quote "$(secret HEALTHCHECK_API_KEY || true)")"
        printf 'NTFY_URL=%s\n' "$(rt_quote "$(ntfy_url "$(secret NTFY_TOPIC || true)")")"
        printf 'HOST_TAILSCALE=%s\n' "$(rt_quote "$(answer HOST_TAILSCALE || echo auto)")"
        printf 'MACHINE_ROLE=%s\n' "$(rt_quote "$(answer MACHINE_ROLE || echo server)")"
        printf 'HOME_ROUTER=%s\n' "$(rt_quote "$(answer HOME_ROUTER || true)")"
        printf 'BACKUP_PROJECTS=%s\n' "$(rt_quote "$ordered")"
        # Modules without a compose project, in backup order: backup-all and update-all run
        # their backup-<module> and update-<module> scripts, where they have one
        native=''
        for m in $(by_backup_order "$@"); do
            [ -z "$(mod_conf "$m" PROJECT)" ] && native=$(list_add "$native" "$m")
        done
        printf 'NATIVE_MODULES=%s\n' "$(rt_quote "$native")"
        printf 'APPS_DIR=%s\n' "$(rt_quote "$(apps_dir)")"
        printf 'BACKUP_DRIVE=%s\n' "$(rt_quote "$(answer BACKUP_DRIVE || true)")"
        # For check-health: each drive the projects keep files on, with those folders
        # (drive|folder, folder...), and the folders on this Mac's own disk
        printf 'MEDIA_VOLUMES=(\n'
        for p in $projects; do project_folders "$p" "$@"; done | awk 'NF && !seen[$0]++' | while IFS= read -r f; do
            vol=$(volume_of "$f")
            [ -n "$vol" ] && printf '%s|%s\n' "$vol" "$f"
        done | awk -F'|' '{ if (!($1 in v)) { o[++n] = $1; v[$1] = $2 } else v[$1] = v[$1] ", " $2 }
            END { for (i = 1; i <= n; i++) print o[i] "|" v[o[i]] }' | while IFS= read -r line; do
            printf '    %s\n' "$(rt_quote "$line")"
        done
        printf ')\n'
        printf 'LOCAL_MEDIA=(\n'
        for p in $projects; do project_folders "$p" "$@"; done | awk 'NF && !seen[$0]++' | while IFS= read -r f; do
            [ -z "$(volume_of "$f")" ] && printf '    %s\n' "$(rt_quote "$f")"
        done
        printf ')\n'
        printf 'KEEP=8\nEXTERNAL_KEEP=26\n'
        # Per project, from its modules' module.conf: what backups leave out and check for, and
        # the check to run after a restore or an update
        for p in $projects; do
            printf 'VOLUMES_%s=%s\n' "${p//-/_}" "$(rt_quote "$(project_volumes "$p" "$@")")"
            for key in BACKUP_EXCLUDE BACKUP_EXPECT AFTER_START; do
                val=''
                for m in "$@"; do
                    [ "$(mod_conf "$m" PROJECT)" = "$p" ] || continue
                    line=$(mod_conf "$m" "$key")
                    [ -n "$line" ] && val="${val:+$val }$line"
                done
                printf '%s_%s=%s\n' "$key" "${p//-/_}" "$(rt_quote "$val")"
            done
        done
        printf 'NATIVE_APPS=(\n'
        for m in "$@"; do
            native=$(mod_conf "$m" NATIVE_HEALTH)
            [ -n "$native" ] || continue
            # @LOGS@ in a line is ~/server/logs (where the kit's jobs write)
            printf '%s\n' "${native//@LOGS@/$SERVER_DIR/logs}" | tr ';' '\n' | while IFS= read -r line; do
                [ -n "$line" ] && printf '    %s\n' "$(rt_quote "$line")"
            done
        done
        printf ')\n'
        # For show-logins: name|address|this Mac's address|user|key|what the key is. Only the
        # keys' names: show-logins reads their values when it runs.
        printf 'LOGINS=(\n'
        login_lines "$@" | while IFS= read -r line; do printf '    %s\n' "$(rt_quote "$line")"; done
        printf ')\n'
    } | write_generated "$(plan_out "$RUNTIME_CONF")" 600
    if in_plan; then
        plan_diff_file "$RUNTIME_CONF" "$(plan_out "$RUNTIME_CONF")" "$(tilde "$RUNTIME_CONF")"
        plan_same_report
    fi
}

# Each module's logins file, with the app's addresses from its urls file: the Tailscale one when
# its node is known, and this Mac's
# shellcheck disable=SC2094  # reads the logins file on fd 3; only prints its name
login_lines() {     # modules... -> name|address|local|user|key|what lines
    local m f name user key what when url ts tsurl
    for m in "$@"; do
        f="$(mod_dir "$m")/logins"
        [ -f "$f" ] || continue
        while IFS='|' read -r name user key what when <&3; do
            case "$name" in ''|'#'*) continue ;; esac
            when_ok "$when" || continue
            url='' ts='' tsurl=''
            [ -f "$(mod_dir "$m")/urls" ] && IFS='|' read -r url ts <<EOF
$(awk -F'|' -v n="$name" '$1 == n { print $2 "|" $3; exit }' "$(mod_dir "$m")/urls")
EOF
            [ -z "$ts" ] || tsurl=$(ts_url "${ts%%:*}" "${ts#*:}")
            printf '%s|%s|%s|%s|%s|%s\n' "$name" "${tsurl:-$url}" "$url" "$user" "$key" "${what:-password}"
        done 3<"$f"
    done
}

# ---------------------------------------------------------------- launchd jobs

# shellcheck disable=SC2094  # reads the jobs file on fd 3; only prints its name
job_lines() {       # modules... -> name|schedule|command lines (conditions applied)
    local m f name interval cmd when
    for m in "$@"; do
        f="$(mod_dir "$m")/jobs"
        [ -f "$f" ] || continue
        while IFS='|' read -r name interval cmd when <&3; do
            case "$name" in ''|'#'*) continue ;; esac
            [[ $name =~ ^[a-z0-9][a-z0-9-]*$ ]] || die "$(tilde "$f"): bad job name '$name'"
            [[ $interval =~ ^([0-9]+|always|login|weekly:[0-6]:([01][0-9]|2[0-3]):[0-5][0-9])$ ]] \
                || die "$(tilde "$f"): bad schedule '$interval' for $name"
            [ -n "$cmd" ] || die "$(tilde "$f"): no command for $name"
            when_ok "$when" || continue
            printf '%s|%s|%s\n' "$name" "$interval" "$cmd"
        done 3<"$f"
    done
}

xml_esc() { printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }

job_plist() {       # name schedule command...
    local name=$1 interval=$2 arg log
    shift 2
    log=$(xml_esc "$SERVER_DIR/logs/$name.log")
    printf '%s\n' '<?xml version="1.0" encoding="UTF-8"?>' \
        '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">' \
        '<!-- Generated by mac-server-kit (./kit install). Do not edit. -->' \
        '<plist version="1.0">' '<dict>' \
        '    <key>Label</key>' "    <string>$KIT_JOB_PREFIX.$name</string>" \
        '    <key>ProgramArguments</key>' '    <array>'
    printf '        <string>%s</string>\n' "$(xml_esc "$SERVER_DIR/bin/$1")"
    shift
    for arg in "$@"; do printf '        <string>%s</string>\n' "$(xml_esc "$arg")"; done
    printf '%s\n' '    </array>'
    case "$interval" in
        weekly:*)
            local d h m
            IFS=: read -r _ d h m <<<"$interval"
            printf '%s\n' '    <key>StartCalendarInterval</key>' '    <dict>' \
                '        <key>Weekday</key>' "        <integer>$d</integer>" \
                '        <key>Hour</key>' "        <integer>$((10#$h))</integer>" \
                '        <key>Minute</key>' "        <integer>$((10#$m))</integer>" '    </dict>' ;;
        always)
            printf '%s\n' '    <key>RunAtLoad</key>' '    <true/>' \
                '    <key>KeepAlive</key>' '    <dict>' '        <key>SuccessfulExit</key>' '        <false/>' '    </dict>' \
                '    <key>ThrottleInterval</key>' '    <integer>30</integer>' ;;
        login)
            printf '%s\n' '    <key>RunAtLoad</key>' '    <true/>' ;;
        *)
            printf '%s\n' '    <key>StartInterval</key>' "    <integer>$interval</integer>" \
                '    <key>RunAtLoad</key>' '    <true/>' ;;
    esac
    printf '%s\n' '    <key>StandardOutPath</key>' "    <string>$log</string>" \
        '    <key>StandardErrorPath</key>' "    <string>$log</string>" \
        '</dict>' '</plist>'
}

job_when() {        # schedule -> how it reads in the install's output
    case "$1" in
        weekly:*)
            local d h m
            IFS=: read -r _ d h m <<<"$1"
            set -- Sunday Monday Tuesday Wednesday Thursday Friday Saturday
            shift "$d"
            printf 'weekly, %s %s:%s' "$1" "$h" "$m" ;;
        always) printf 'always running (starts at login, again after a crash)' ;;
        login) printf 'at login' ;;
        *) printf 'every %s min' "$(( $1 / 60 ))" ;;
    esac
}

job_load() {        # label plist -> (re)load it into this user's launchd session
    local domain
    domain="gui/$(id -u)"
    klaunchctl bootout "$domain/$1" >/dev/null 2>&1 || true
    klaunchctl bootstrap "$domain" "$2" >/dev/null 2>&1
}

jobs_install() {    # modules...
    local dir lines name interval cmd label f new tmp names='' p
    dir=$(launch_agents)
    lines=$(job_lines "$@") || exit 1
    if [ -n "$lines" ] && ! in_plan; then
        mkdir -p "$dir" || die "could not create $dir"
    fi
    while IFS='|' read -r name interval cmd; do
        [ -n "$name" ] || continue
        label=$KIT_JOB_PREFIX.$name
        f=$dir/$label.plist
        names=$(list_add "$names" "$name")
        # shellcheck disable=SC2086  # the command's words are its arguments
        new=$(job_plist "$name" "$interval" $cmd)
        if [ -f "$f" ] && [ "$(cat "$f")" = "$new" ] && klaunchctl print "gui/$(id -u)/$label" >/dev/null 2>&1; then
            note "Job $name: $(job_when "$interval") (already loaded)"
            continue
        fi
        if in_plan; then
            if [ ! -f "$f" ]; then
                plan_add "Load job $name: $(job_when "$interval") ($label)"
            elif [ "$(cat "$f")" = "$new" ]; then
                plan_add "Load job $name: $(job_when "$interval") (its plist is there, but launchd hasn't loaded it)"
            else
                printf '%s\n' "$new" | write_generated "$(plan_out "$f")"
                plan_diff_file "$f" "$(plan_out "$f")" "job $name ($(tilde "$f")), which is then reloaded"
                case "$interval" in always) plan_add "Restart $name (its job is reloaded)" ;; esac
            fi
            continue
        fi
        printf '%s\n' "$new" | write_generated "$f"
        if job_load "$label" "$f"; then
            ok "Job $name: $(job_when "$interval") ($label)"
        else
            warn "Job $name: launchd didn't load it. Try: launchctl bootstrap gui/$(id -u) $(tilde "$f")"
        fi
    done <<EOF2
$lines
EOF2
    for f in "$dir/$KIT_JOB_PREFIX".*.plist; do
        [ -f "$f" ] || continue
        p=${f##*/}; p=${p#"$KIT_JOB_PREFIX".}; p=${p%.plist}
        in_list "$p" "$names" && continue
        if in_plan; then plan_add "Unload job $p and remove its plist (no enabled module has it)"; continue; fi
        klaunchctl bootout "gui/$(id -u)/$KIT_JOB_PREFIX.$p" >/dev/null 2>&1 || true
        rm -f "$f"
        ok "Job $p: removed (no enabled module has it)"
    done
}

runtime_install() { # modules...
    bin_install "$@"
    runtime_write "$@"
    jobs_install "$@"
    in_plan && plan_other_jobs
    return 0
}

# A plan's note of launchd jobs that aren't the kit's but look like they run the same things (an
# older setup's): they may overlap with the kit's own
plan_other_jobs() {
    local f
    for f in "$(launch_agents)"/*.plist; do
        [ -f "$f" ] || continue
        case "${f##*/}" in "$KIT_JOB_PREFIX".*) continue ;; esac
        grep -qiE 'plex|jellyfin|glances|ollama|docker|compose|backup|orbstack|media' "$f" 2>/dev/null || continue
        plan_flag "Another launchd job, $(tilde "$f"), mentions $(grep -oiE 'plex|jellyfin|glances|ollama|docker|compose|backup|orbstack|media' "$f" | head -n 1): check that it doesn't also do what the kit's jobs do"
    done
}
